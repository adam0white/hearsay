/** Exhausted speakers stay silent instead of repeating a stem during the same day. */
export function say(
  s: State,
  id: string,
  kind: 'opening' | 'reply' | 'refusal',
  detail = '',
): string | undefined {
  const pool = VOICES[id]?.[kind === 'refusal' ? 'refuse' : kind === 'opening' ? 'open' : 'reply'];
  if (!pool) return undefined;
  const key = `voice:${Math.floor(s.minute / 1440)}:${id}`;
  s.voiceUsed[key] ??= [];
  const used = s.voiceUsed[key];
  const stems =
    s.version >= 4 && id === 'derya' && kind === 'opening'
      ? pool.map((stem) =>
          stem === 'My shift starts a bit later.' ? 'My night shift is over. I need to sleep soon.' : stem,
        )
      : pool;
  const stem = stems.find((p) => !used.includes(p));
  if (!stem) return undefined;
  used.push(stem);
  return detail ? `${stem} ${detail}` : stem;
}

/** A report about character, rather than a trait label read aloud. No final period. */
export function claimText(name: string, trait: string, value: boolean): string {
  const phrases: Record<string, readonly [string, string]> = {
    honest: ['tells the truth', 'doesn’t always tell the truth'],
    dishonest: ['doesn’t always tell the truth', 'tells the truth'],
    reliable: ['keeps promises', 'doesn’t keep promises'],
    unreliable: ['doesn’t keep promises', 'keeps promises'],
    generous: ['gives what they can spare', 'doesn’t give much away'],
    stingy: ['doesn’t give much away', 'gives what they can spare'],
    kind: ['treats people well', 'doesn’t treat people well'],
    cruel: ['doesn’t treat people well', 'treats people well'],
    hardworking: ['puts in the work', 'doesn’t put much effort in'],
    lazy: ['doesn’t put much effort in', 'puts in the work'],
    owes: ['still has money to pay back', 'has no debt left to pay'],
  };
  const phrase = phrases[trait]?.[value ? 0 : 1];
  return phrase
    ? `${name} ${phrase}`
    : `${name} ${value ? 'has' : 'does not have'} a reputation for being ${trait}`;
}

