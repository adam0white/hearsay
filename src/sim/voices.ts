/** Exhausted speakers stay silent instead of repeating a stem during the same day. */
export function say(
  s: State,
  id: string,
  kind: 'opening' | 'reply' | 'refusal',
  detail = '',
): string | undefined {
  const pool = VOICES[id]?.[kind === 'refusal' ? 'refuse' : kind === 'opening' ? 'open' : 'reply'];
  if (!pool) return undefined;
  const key = `voice:${Math.floor(s.minute / 1440)}:${id}`;
  s.voiceUsed[key] ??= [];
  const used = s.voiceUsed[key];
  const stem = pool.find((p) => !used.includes(p));
  if (!stem) return undefined;
  used.push(stem);
  return detail ? `${stem} ${detail}` : stem;
}
